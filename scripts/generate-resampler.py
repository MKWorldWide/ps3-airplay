#!/usr/bin/env python3
"""Generate the bounded 160-phase, 64-tap Blackman sinc table (no runtime math)."""
from pathlib import Path
import math
rows=[]
for phase in range(160):
    frac=phase/160
    a=[]
    for k in range(64):
        x=k+frac-31
        sinc=1 if abs(x)<1e-12 else math.sin(math.pi*x)/(math.pi*x)
        w=0.42+0.5*math.cos(math.pi*x/32)+0.08*math.cos(2*math.pi*x/32) if abs(x)<32 else 0
        a.append(sinc*w)
    total=sum(a)
    rows.append(" {"+", ".join(format(v/total,'.9e')+'f' for v in a)+"}")
Path(__file__).resolve().parents[1].joinpath('src/audio/resampler_coefficients.h').write_text(
    '/* Generated by scripts/generate-resampler.py; 31-input-frame causal delay. */\n'
    'static const float raop_src_coefficients[160][64] = {\n'+',\n'.join(rows)+'\n};\n')
